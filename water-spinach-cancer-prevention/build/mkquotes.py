def strip(t):
    m=re.match(r'^((?:@\w+\s+)+)',t)
    return (t[m.end():], m.group(1).strip()) if m else (t,'')
def esc(s):
    out=[];i=0
    parts=re.split(r'(https://t\.co/\w+)',s)
    for k,p in enumerate(parts):
        if k%2: out.append('\\url{'+p+'}'); continue
        p=p.replace('\\','\\textbackslash{}')
        for a,b in [('{','\\{'),('}','\\}'),('$','\\$'),('&','\\&'),('#','\\#'),('_','\\_'),('%','\\%'),('~','\\textasciitilde{}'),('^','\\textasciicircum{}')]: p=p.replace(a,b)
        p=p.replace('"','\\textquotedbl{}').replace('β','$\\beta$').replace('...','.\\,.\\,.')
        for e,n in EMOJI.items(): p=p.replace(e,'\\emojinote{'+n+'}')
        p=p.replace('\n\n','\\par ').replace('\n','\\newline ')
        out.append(p)
    return ''.join(out)
